// Writes the GitHub issue form for repeater corrections from the field list
// in src/lib/repeaters/correction.ts, so the form, the site's prefilled link
// and the parser cannot drift apart. A test checks the committed file.
//   node scripts/repeaters/issue-form.ts
import { writeFile } from 'node:fs/promises';
import { FIELDS, FORM_FILE, MODE_CHOICES, ON_AIR_CHOICES, TONE_CHOICES } from '../../src/lib/repeaters/correction.ts';

export const FORM_PATH = `.github/ISSUE_TEMPLATE/${FORM_FILE}`;

// JSON strings are valid YAML, which saves escaping by hand.
const q = (s: string) => JSON.stringify(s);

interface Field {
  type: 'input' | 'textarea' | 'dropdown' | 'checkboxes' | 'markdown';
  id?: string;
  label?: string;
  description?: string;
  placeholder?: string;
  options?: readonly string[];
  required?: boolean;
  markdown?: string;
}

function field(f: Field): string {
  const lines = [`  - type: ${f.type}`];
  if (f.id) lines.push(`    id: ${f.id}`);
  lines.push('    attributes:');
  if (f.markdown) lines.push(`      value: ${q(f.markdown)}`);
  if (f.label) lines.push(`      label: ${q(f.label)}`);
  if (f.description) lines.push(`      description: ${q(f.description)}`);
  if (f.placeholder) lines.push(`      placeholder: ${q(f.placeholder)}`);
  if (f.options && f.type === 'checkboxes') {
    lines.push('      options:', ...f.options.map((o) => `        - label: ${q(o)}`));
  } else if (f.options) {
    lines.push('      options:', ...f.options.map((o) => `        - ${q(o)}`));
    lines.push('      default: 0');
  }
  if (f.required !== undefined) lines.push('    validations:', `      required: ${f.required}`);
  return lines.join('\n');
}

export function renderIssueForm(): string {
  const F = FIELDS;
  const fields: Field[] = [
    {
      type: 'markdown',
      markdown:
        'Obrigado por ajudar! Preencha só o que você sabe; o resto pode ficar em branco. ' +
        'Um mantenedor confere a sugestão e, quando aprovada, o mapa é atualizado sozinho.',
    },
    { type: 'input', id: F.repeater.id, label: F.repeater.label, description: 'Indicativo@saída, como o mapa mostra. Para uma repetidora nova, o indicativo e a frequência de saída.', placeholder: 'PY1BEU@147.150', required: true },
    { type: 'textarea', id: F.context.id, label: F.context.label, description: 'Preenchido pelo site. Pode deixar como está.' },
    { type: 'dropdown', id: F.tone.id, label: F.tone.label, description: 'O tom (CTCSS) que a repetidora exige para abrir.', options: TONE_CHOICES },
    { type: 'input', id: F.dcs.id, label: F.dcs.label, description: 'Só se a repetidora usa DCS: três dígitos.', placeholder: '023' },
    { type: 'input', id: F.position.id, label: F.position.label, description: 'Onde fica a antena (não a cidade): latitude e longitude.', placeholder: '-22,4547 -43,1729' },
    { type: 'checkboxes', id: F.modes.id, label: F.modes.label, description: 'Marque os modos que a repetidora aceita.', options: MODE_CHOICES },
    { type: 'dropdown', id: F.onAir.id, label: F.onAir.label, options: ON_AIR_CHOICES },
    { type: 'input', id: F.input.id, label: F.input.label, description: 'Frequência de entrada em MHz, se a repetidora não está no mapa.', placeholder: '147,750' },
    { type: 'input', id: F.place.id, label: F.place.label, placeholder: 'Petrópolis/RJ' },
    { type: 'textarea', id: F.notes.id, label: F.notes.label, description: 'Local, horários, link de internet, quem mantém... Aparece no site.' },
    { type: 'textarea', id: F.source.id, label: F.source.label, description: 'Por exemplo: "testei no ar em 09/11/2026", "sou do clube que mantém", "anúncio do clube".', required: true },
    { type: 'input', id: F.callsign.id, label: F.callsign.label, description: 'Opcional. Aparece no site como fonte da correção; sem ele, aparece seu usuário do GitHub.', placeholder: 'PU1JAZ' },
  ];
  return [
    '# Generated by scripts/repeaters/issue-form.ts from src/lib/repeaters/correction.ts. Do not edit by hand.',
    `name: ${q('Correção de repetidora')}`,
    `description: ${q('Informe subtom, posição, modos ou se está no ar, ou uma repetidora que falta no mapa.')}`,
    `title: ${q('Correção: ')}`,
    'labels: ["correcao"]',
    'body:',
    ...fields.map(field),
    '',
  ].join('\n');
}

if (import.meta.main) {
  await writeFile(FORM_PATH, renderIssueForm());
  console.log(`wrote ${FORM_PATH}`);
}
